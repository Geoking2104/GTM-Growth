#!/usr/bin/env node
/** One static layout, two complete dictionaries. Generated HTML stays deployable without a build server. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseHTML } from "linkedom";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const template = fs.readFileSync(path.join(root, "site/landing/template.html"), "utf8");
const keys = [...new Set([...template.matchAll(/\{\{(t\d+)\}\}/g)].map(match => match[1]))].sort();
const escape = value => String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
const check = process.argv.includes("--check");
for (const locale of ["en", "fr"]) {
  const copy = JSON.parse(fs.readFileSync(path.join(root, `site/landing/${locale}.json`), "utf8"));
  if (JSON.stringify(Object.keys(copy).sort()) !== JSON.stringify(keys)) throw new Error(`${locale}: translation keys differ from the template`);
  for (const [key, value] of Object.entries(copy)) if (typeof value !== "string" || !value.trim()) throw new Error(`${locale}: empty translation ${key}`);
  const canonical = `https://gtm.kayroslab.com/${locale === "fr" ? "fr/" : ""}`;
  const config = { locale, canonical, privacy: locale === "fr" ? "/fr/confidentialite.html" : "/privacy.html", active_en: locale === "en" ? 'aria-current="page"' : "", active_fr: locale === "fr" ? 'aria-current="page"' : "" };
  let html = template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (key in copy) return escape(copy[key]);
    if (key in config) return config[key];
    throw new Error(`Unknown template key: ${key}`);
  });
  const { document } = parseHTML(html);
  const structuredData = { "@context": "https://schema.org", "@graph": [
    { "@type": "WebSite", name: "GTM Growth", url: canonical, inLanguage: locale, description: copy.t361 },
    { "@type": "SoftwareApplication", name: "GTM Growth", applicationCategory: "DeveloperApplication", operatingSystem: "Node.js 20+", url: canonical, codeRepository: "https://github.com/Geoking2104/GTM-Growth", license: "https://www.apache.org/licenses/LICENSE-2.0" },
    { "@type": "FAQPage", mainEntity: [...document.querySelectorAll("#faq details")].map(item => ({ "@type": "Question", name: item.querySelector("summary").textContent, acceptedAnswer: { "@type": "Answer", text: item.querySelector("p").textContent } })) },
  ] };
  const social = `<meta property="og:type" content="website">\n<meta property="og:locale" content="${locale === "fr" ? "fr_FR" : "en_US"}">\n<meta property="og:title" content="${escape(copy.t001)}">\n<meta property="og:description" content="${escape(copy.t361)}">\n<meta property="og:url" content="${canonical}">\n<meta property="og:image" content="https://gtm.kayroslab.com/fr/assets/logo-rocket.png">\n<meta name="twitter:card" content="summary">`;
  html = html.replace("</head>", `${social}\n<script type="application/ld+json">${JSON.stringify(structuredData).replaceAll("<", "\\u003c")}</script>\n</head>`);
  html = html.replace(/<!doctype html>/i, "<!doctype html>\n<!-- Generated by scripts/render-landing.mjs; edit site/landing/template.html and the locale dictionaries. -->");
  html = html.replace(/[\t ]+$/gm, "").trimEnd() + "\n";
  const target = path.join(root, locale === "fr" ? "site/fr/index.html" : "site/index.html");
  if (check) {
    if (fs.readFileSync(target, "utf8") !== html) throw new Error(`${target} is stale; run node scripts/render-landing.mjs`);
  } else fs.writeFileSync(target, html);
}
console.log(`Landing ${check ? "check" : "render"} OK: shared layout and ${keys.length} complete translations per locale`);
