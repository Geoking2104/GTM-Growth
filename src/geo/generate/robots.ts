import { AI_BOTS, CITATION_BOTS } from "../config.js";
import { classifyBot, parseRobots } from "../robots.js";

export interface RobotsFixOptions {
  baseUrl: string;
  /** Current robots.txt content, when one already exists. */
  existing?: string | null;
  sitemaps?: string[];
}

export interface RobotsFix {
  /** Ready-to-deploy file (existing content preserved, missing groups appended). */
  content: string;
  /** Bots that got a new explicit `Allow` group. */
  added: string[];
  /** Bots already covered by a wildcard `Allow` (no explicit rule). */
  coveredByWildcard: string[];
  /** Bots explicitly disallowed — the existing rules must be edited by hand. */
  blocked: string[];
  /** True when the file can be written as-is without touching existing rules. */
  appendOnly: boolean;
}

/**
 * Produce a robots.txt that lets AI crawlers in, without rewriting rules the
 * site owner wrote on purpose: blocked bots are reported, not overridden.
 */
export function generateRobotsFix(options: RobotsFixOptions): RobotsFix {
  const existing = (options.existing ?? "").replace(/^\uFEFF/, "").trimEnd();
  const groups = existing ? parseRobots(existing) : {};

  const added: string[] = [];
  const coveredByWildcard: string[] = [];
  const blocked: string[] = [];

  for (const bot of Object.keys(AI_BOTS)) {
    const result = classifyBot(bot, groups);
    if (result.status === "allowed" && result.viaWildcard) coveredByWildcard.push(bot);
    else if (result.status === "blocked") blocked.push(bot);
    else if (result.status === "missing") added.push(bot);
  }

  // Citation bots deserve an explicit rule even when the wildcard allows them.
  for (const bot of CITATION_BOTS) {
    if (coveredByWildcard.includes(bot) && !added.includes(bot)) {
      added.push(bot);
      coveredByWildcard.splice(coveredByWildcard.indexOf(bot), 1);
    }
  }

  const blocks: string[] = [];
  for (const bot of added) {
    blocks.push(`User-agent: ${bot}`, "Allow: /", "");
  }

  const sitemapLines = [
    ...new Set(
      (options.sitemaps?.length
        ? options.sitemaps
        : [`${new URL(options.baseUrl).origin}/sitemap.xml`]
      ).filter((url) => /^https?:\/\//i.test(url))
    ),
  ].map((url) => `Sitemap: ${url}`);

  const header = [
    "# AI crawler access — generated by google-growth",
    "# Training, search and on-demand user fetchers are listed explicitly so",
    "# citation eligibility does not depend on the wildcard group.",
    "",
  ].join("\n");

  const parts: string[] = [];
  if (existing) parts.push(existing);
  if (blocks.length) parts.push(`${existing ? "\n" : ""}${header}${blocks.join("\n").trimEnd()}`);
  if (sitemapLines.length && !sitemapLines.every((line) => existing.includes(line.trim()))) {
    parts.push(`\n${sitemapLines.filter((line) => !existing.includes(line)).join("\n")}`);
  }

  return {
    content: `${parts.join("\n").replace(/\n{3,}/g, "\n\n").trim()}\n`,
    added,
    coveredByWildcard,
    blocked,
    appendOnly: existing.length > 0,
  };
}
